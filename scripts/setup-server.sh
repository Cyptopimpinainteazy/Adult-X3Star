#!/usr/bin/env bash
# x3STAR production setup for a Debian/Ubuntu server.
#
#   git clone -b feature/x3star-platform https://github.com/Cyptopimpinainteazy/Adult-X3Star.git ~/x3star
#   bash ~/x3star/scripts/setup-server.sh
# The repo is private, so the machine needs GitHub access (e.g. `gh auth login`) for the clone.
#
# What it does (safe to re-run; it updates instead of duplicating):
#   1. Installs Node.js 22 if the installed version is older than 22.13
#   2. Clones or updates the app in ~/x3star (branch feature/x3star-platform)
#   3. Creates .env on first run (asks for the admin email + password; generates the rest)
#   4. Installs the app as a systemd service "x3star" (starts on boot, restarts on crash)
#   5. Installs Caddy as an HTTPS reverse proxy for the domain (automatic certificates)
#   6. Opens ports 80/443 in ufw if ufw is active
#   7. Prints the public IP to point the domain's DNS at
set -euo pipefail

DOMAIN="${DOMAIN:-x3star.live}"
BRANCH="${BRANCH:-feature/x3star-platform}"
REPO="${REPO:-https://github.com/Cyptopimpinainteazy/Adult-X3Star.git}"
APP_DIR="${APP_DIR:-$HOME/x3star}"
PORT="${PORT:-6969}"
RUN_USER="$(id -un)"

say()  { printf '\n\033[1;35m▸ %s\033[0m\n' "$*"; }
die()  { printf '\n\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }
need_sudo() { if [ "$(id -u)" -ne 0 ]; then sudo -v || die "This script needs sudo for packages, systemd and Caddy."; fi; }
SUDO=""; [ "$(id -u)" -ne 0 ] && SUDO="sudo"
# Wait up to 10 minutes if unattended-upgrades (or another apt) holds the dpkg lock, instead of failing.
APT="$SUDO apt-get -o DPkg::Lock::Timeout=600"

command -v apt-get >/dev/null || die "This script supports Debian/Ubuntu (apt-get) only."
need_sudo

# ── 1. Node.js ≥ 22.13 ───────────────────────────────────────────────
node_ok() { command -v node >/dev/null && node -e 'const [a,b]=process.versions.node.split(".").map(Number);process.exit(a>22||(a===22&&b>=13)?0:1)'; }
if node_ok; then
  say "Node.js $(node -v) is new enough"
else
  say "Installing Node.js 22"
  $APT update -qq
  $APT install -y -qq ca-certificates curl gnupg git
  if [ -n "$SUDO" ]; then curl -fsSL https://deb.nodesource.com/setup_22.x | sudo -E bash -; else curl -fsSL https://deb.nodesource.com/setup_22.x | bash -; fi
  $APT install -y -qq nodejs
  node_ok || die "Node.js install did not produce v22.13+ (got $(node -v 2>/dev/null || echo none))."
fi
command -v git >/dev/null || $APT install -y -qq git

# ── 2. App code ─────────────────────────────────────────────────────
if [ -d "$APP_DIR/.git" ]; then
  say "Updating $APP_DIR"
  git -C "$APP_DIR" fetch -q origin "$BRANCH"
  git -C "$APP_DIR" checkout -q "$BRANCH"
  git -C "$APP_DIR" pull -q --ff-only origin "$BRANCH"
else
  [ -e "$APP_DIR" ] && die "$APP_DIR exists but is not a git clone. Move it aside or set APP_DIR=/another/path."
  say "Cloning into $APP_DIR"
  git clone -q -b "$BRANCH" "$REPO" "$APP_DIR"
fi
cd "$APP_DIR"
say "Installing dependencies"
npm ci --omit=dev --no-audit --no-fund --loglevel=error

# ── 3. .env (first run only) ─────────────────────────────────────────
if [ ! -f .env ]; then
  say "First run: creating .env"
  ADMIN_EMAIL=""
  while ! printf '%s' "$ADMIN_EMAIL" | grep -Eq '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]{2,}$'; do
    read -r -p "  Admin email: " ADMIN_EMAIL < /dev/tty
  done
  ADMIN_PASSWORD=""
  while [ "${#ADMIN_PASSWORD}" -lt 12 ]; do
    read -r -s -p "  Admin password (12+ characters): " ADMIN_PASSWORD < /dev/tty; echo
    [ "${#ADMIN_PASSWORD}" -lt 12 ] && echo "  Too short."
  done
  rand() { node -e "process.stdout.write(require('crypto').randomBytes($1).toString('base64url'))"; }
  umask 077
  cat > .env <<EOF
# Generated by scripts/setup-server.sh on $(date -u +%Y-%m-%dT%H:%MZ)
PORT=$PORT
# Only Caddy (same machine) talks to the app; the internet reaches it through HTTPS.
HOST=127.0.0.1
NODE_ENV=production
TRUST_PROXY=1
COOKIE_SECURE=1
SESSION_DAYS=30

DATA_DIR=./data
MAX_UPLOAD_MB=50
AUTO_APPROVE_UPLOADS=0

ADMIN_EMAIL=$ADMIN_EMAIL
ADMIN_PASSWORD=$ADMIN_PASSWORD

# Demo creators fill the site until real creators join. Set 0 before the first start to skip them.
SEED_DEMO=1
DEMO_PASSWORD=$(rand 12)
# Simulated chat/gifts make rooms look busy. Off for a public site; set 1 only for demos.
DEMO_TRAFFIC=0

PAYMENTS_MODE=test
CLICK_SALT=$(rand 24)
EOF
  echo "  .env written (readable only by $RUN_USER)."
else
  say ".env already exists — leaving it unchanged"
fi
APP_PORT="$(grep -E '^PORT=' .env | tail -1 | cut -d= -f2)"; APP_PORT="${APP_PORT:-$PORT}"

# ── 4. systemd service ──────────────────────────────────────────────
say "Installing systemd service x3star"
NODE_BIN="$(command -v node)"
$SUDO tee /etc/systemd/system/x3star.service >/dev/null <<EOF
[Unit]
Description=x3STAR
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$RUN_USER
WorkingDirectory=$APP_DIR
ExecStart=$NODE_BIN server/index.js
Restart=always
RestartSec=3
Environment=NODE_ENV=production
NoNewPrivileges=true
ProtectSystem=full
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
# Stop any copy started by hand so the port is free
pkill -u "$RUN_USER" -f "node server/index.js" 2>/dev/null || true
sleep 1
$SUDO systemctl daemon-reload
$SUDO systemctl enable -q x3star
$SUDO systemctl restart x3star
for i in $(seq 1 20); do
  curl -fsS "http://127.0.0.1:$APP_PORT/api/health" >/dev/null 2>&1 && break
  sleep 1
  [ "$i" -eq 20 ] && { $SUDO journalctl -u x3star -n 40 --no-pager; die "x3star did not come up on port $APP_PORT (log above)."; }
done
say "x3star is running on 127.0.0.1:$APP_PORT"

# ── 5. Caddy (HTTPS) ────────────────────────────────────────────────
if ! command -v caddy >/dev/null; then
  say "Installing Caddy"
  $APT install -y -qq debian-keyring debian-archive-keyring apt-transport-https curl gnupg
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | $SUDO gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' | $SUDO tee /etc/apt/sources.list.d/caddy-stable.list >/dev/null
  $APT update -qq
  $APT install -y -qq caddy
fi
say "Configuring Caddy for $DOMAIN and www.$DOMAIN"
[ -f /etc/caddy/Caddyfile ] && $SUDO cp /etc/caddy/Caddyfile "/etc/caddy/Caddyfile.bak.$(date +%s)"
$SUDO tee /etc/caddy/Caddyfile >/dev/null <<EOF
$DOMAIN, www.$DOMAIN {
	encode zstd gzip
	reverse_proxy 127.0.0.1:$APP_PORT
	log {
		output file /var/log/caddy/x3star.log {
			roll_size 20mb
			roll_keep 5
		}
	}
}
EOF
$SUDO mkdir -p /var/log/caddy && $SUDO chown caddy:caddy /var/log/caddy 2>/dev/null || true
$SUDO caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null
$SUDO systemctl enable -q caddy
$SUDO systemctl reload caddy 2>/dev/null || $SUDO systemctl restart caddy

# ── 6. Firewall ─────────────────────────────────────────────────────
if command -v ufw >/dev/null && $SUDO ufw status | grep -q "Status: active"; then
  say "Opening ports 80 and 443 in ufw"
  $SUDO ufw allow 80/tcp >/dev/null
  $SUDO ufw allow 443/tcp >/dev/null
  $SUDO ufw delete allow "$APP_PORT/tcp" >/dev/null 2>&1 || true
fi

# ── 7. Where to point DNS ───────────────────────────────────────────
PUBLIC_IP="$(curl -4 -fsS --max-time 8 https://api.ipify.org || curl -4 -fsS --max-time 8 https://ifconfig.me || true)"
LOCAL_IPS="$(hostname -I 2>/dev/null | tr ' ' '\n' | grep -E '^[0-9.]+$' | tr '\n' ' ')"
say "Done"
echo "  Public IP:  ${PUBLIC_IP:-could not detect}"
echo "  This box:   ${LOCAL_IPS:-unknown}"
if [ -n "$PUBLIC_IP" ] && ! printf '%s' "$LOCAL_IPS" | grep -qw "$PUBLIC_IP"; then
  echo "  ⚠ This machine is behind a router (NAT). Forward TCP 80 and 443 on the router to $(printf '%s' "$LOCAL_IPS" | awk '{print $1}')."
fi
echo
echo "  DNS for $DOMAIN:  A @ → ${PUBLIC_IP:-<public IP>}   A www → ${PUBLIC_IP:-<public IP>}"
echo "  Once DNS points here, Caddy fetches the HTTPS certificate on its own (give it a minute)."
echo
echo "  Logs:     journalctl -u x3star -f        Restart: sudo systemctl restart x3star"
echo "  Update:   bash $APP_DIR/scripts/setup-server.sh"
if [ -f "$APP_DIR/.env" ] && grep -q '^SEED_DEMO=1' "$APP_DIR/.env"; then
  echo "  Demo logins were printed in the first start log:  journalctl -u x3star | grep -A3 'first-run accounts'"
fi
